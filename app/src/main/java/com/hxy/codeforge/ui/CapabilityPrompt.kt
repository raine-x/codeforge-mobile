package com.hxy.codeforge.ui

/**
 * 注入给模型的「客户端渲染能力」说明，以及定位注入段的标记。
 *
 * ## 为什么要有这段
 *
 * 内核的 system prompt 来自 `cfg.SystemPromptFile` 或默认模板，
 * **没有「客户端追加一段说明」的入口**（`/api/config` 只有模型、温度、重试、步数）。
 * 想让模型知道「这个客户端能渲染什么」，唯一不用改内核的通路就是把说明混进上行文本。
 *
 * ## 为什么不能只讲网页
 *
 * 早先这段说明只讲「内嵌可交互网页」，还给了一份适用范围清单
 * （试题、图表、演示、看板……一律可用网页）。后果是**能力面被写窄了**：
 * 模型只知道网页这一种「能玩起来」的呈现方式，于是把本该用原生通道的东西也包成网页 ——
 * 最典型的是：明明宿主有原生播放器与音视频跳转卡片，模型找到一个视频链接时，
 * 仍然写一整页 HTML 去显示它。
 *
 * 修法不是加禁令（prompt-audit 的经验：禁止项会把模型锚定到那个失败形态），
 * 而是**把能力面写全，并给出肯定式的路由**：每种内容对应哪种格式，模型自己按语义选。
 *
 * ## 每条格式都必须与实现对得上
 *
 * 宿主实际支持的通道（改这里之前先读实现，改完再回来核一遍）：
 *
 * | 提示词里的说法 | 实现位置 |
 * |---|---|
 * | 普通 Markdown（段落/列表/表格/代码块/引用） | `ui/chat/OpenRenderMessage.kt` 的块渲染分支 |
 * | LaTeX 公式渲染成图 | `render/RenderIr.kt`（`$`/`$$` 定界，另有 `\(...\)` 归一） |
 * | `![说明](地址)` 图片 | `OpenRenderMessage.kt` 的 image span 分支（独占段=大图，混排=缩略图） |
 * | ` ```image ` / ` ```video ` / ` ```audio ` 围栏首行写地址 | `OpenRenderMessage.kt` 的 `CodeFenceBlock` 按 lang 路由，地址取围栏首个非空行 |
 * | ` ```svg ` 围栏放 SVG 源码 | 同上，另有段落内裸 `<svg>…</svg>` |
 * | `[ ▶视频 地址 ]` / `[ ▶音频 地址 ]` 独占一行 | `ui/chat/MessageBlocks.kt` 的 `MEDIA_JUMP_TAG_REGEX` 与 `MediaJumpCard` |
 * | 完整 HTML 文档 / ` ```html ` 围栏 | `ui/browser/HtmlDetection.kt` + `ui/browser/HtmlBlockView.kt` |
 *
 * 地址既可以是网络链接，也可以是工作区相对路径（如 `attachments/a.png`）——
 * 相对路径由 `MessageBlocks.attachmentFile` 按当前会话工作区解析。
 */

