- 放一段视频或音频 → 视频 / 音频 / 跳转标签格式（一个视频不值得做成网页）。
- 放一张图 → 图片格式。
- 用户要在页面上动手（点按钮、展开收起、填表单、动画演示）→ 才写网页；
  只给人看的静态内容用正文、表格、图片即可。

