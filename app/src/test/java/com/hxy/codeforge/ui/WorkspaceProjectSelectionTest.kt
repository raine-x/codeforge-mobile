package com.hxy.codeforge.ui

import com.hxy.codeforge.ui.files.canOpenDirAsProject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File

class WorkspaceProjectSelectionTest {

    @get:Rule
    val tmp = TemporaryFolder()

    @Test
    fun canonicalPathOrRaw_normalizesDotSegmentsAndBlank() {
        assertEquals("", canonicalPathOrRaw("   "))

        val root = tmp.newFolder("cell")
        val sub = File(root, "workspace/my_app").apply { mkdirs() }
        val nonCanonical = File(root, "workspace/./other/../my_app").absolutePath
        assertEquals(sub.canonicalPath, canonicalPathOrRaw(nonCanonical))
    }

    @Test
    fun sameWorkspacePath_matchesEquivalentPaths() {
        val root = tmp.newFolder("cell")
        val appDir = File(root, "workspace/demo").apply { mkdirs() }
        val alias = "${root.absolutePath}/workspace/./demo"

        assertTrue(sameWorkspacePath(appDir.absolutePath, alias))
        assertFalse(sameWorkspacePath(appDir.absolutePath, File(root, "workspace/other").absolutePath))
        assertFalse(sameWorkspacePath("", appDir.absolutePath))
    }

    @Test
    fun isAutoGeneratedProjectDir_distinguishesManagedAndUserDirs() {
        val workspaceRoot = tmp.newFolder("workspace")
        val autoDir = File(workspaceRoot, "p-1a2b3c4d").apply { mkdirs() }
        val customDir = File(workspaceRoot, "my-folder").apply { mkdirs() }
        val outsideAutoDir = File(tmp.root, "p-1a2b3c4d").apply { mkdirs() }

        assertTrue(isAutoGeneratedProjectDir(autoDir.absolutePath, workspaceRoot.absolutePath))
        assertFalse(isAutoGeneratedProjectDir(customDir.absolutePath, workspaceRoot.absolutePath))
        assertFalse(isAutoGeneratedProjectDir(outsideAutoDir.absolutePath, workspaceRoot.absolutePath))
        assertFalse(isAutoGeneratedProjectDir("", workspaceRoot.absolutePath))
    }

    @Test
    fun canOpenDirAsProject_blocksWorkspacesContainerAndAllowsSubfolders() {
        val cell = tmp.newFolder("cell")
        val workspaces = File(cell, "workspace").apply { mkdirs() }
        val childFolder = File(workspaces, "new_folder").apply { mkdirs() }
        val nestedFolder = File(childFolder, "src").apply { mkdirs() }
        val sdcardFolder = File(cell, "sdcard_demo").apply { mkdirs() }
        val plainFile = File(workspaces, "readme.txt").apply { writeText("hi") }

        assertFalse(canOpenDirAsProject(workspaces, workspaces))
        assertFalse(canOpenDirAsProject(File(cell, "workspace/."), workspaces))
        assertFalse(canOpenDirAsProject(plainFile, workspaces))

        assertTrue(canOpenDirAsProject(childFolder, workspaces))
        assertTrue(canOpenDirAsProject(nestedFolder, workspaces))
        assertTrue(canOpenDirAsProject(sdcardFolder, workspaces))
    }

    @Test
    fun appRoot_allowsNewProjectCreationAndRoutesPickerToWorkspaces() {
        val appRoot = listOf(
            File("src/main/java/com/hxy/codeforge/ui/AppRoot.kt"),
            File("app/src/main/java/com/hxy/codeforge/ui/AppRoot.kt"),
        ).firstOrNull { it.isFile } ?: return

        val src = appRoot.readText()
        assertFalse(
            "openNewProject 不应再以已有空的新项目拦住新建/打开目录弹窗",
            src.contains("openNewProject") && src.substringAfter("val openNewProject").substringBefore("val openWorkspaceFiles").contains("已有空的新项目"),
        )
        assertTrue(
            "NewProjectPanel 选择目录应以 WORKSPACES 起始进入统一文件管理器",
            src.contains("fileManagerInitialRoot = \"WORKSPACES\"") && src.contains("fileManagerPickerMode = true"),
        )
    }
}
